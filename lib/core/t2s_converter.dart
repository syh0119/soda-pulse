  /// Converts Traditional Chinese characters in [input] to Simplified Chinese.
  ///
  /// Characters not present in the lookup table are preserved as-is.
  static String convert(String input) {
    if (input.isEmpty) return input;
    final StringBuffer buffer = StringBuffer();
    for (final int rune in input.runes) {
      final String char = String.fromCharCode(rune);
      buffer.write(_t2sMap[char] ?? char);
    }
    return buffer.toString();
  }

  /// Normalizes [input] by converting Traditional Chinese to Simplified Chinese,
  /// trimming leading/trailing whitespace, and converting to lowercase.
  static String normalize(String input) {
    return convert(input).trim().toLowerCase();
